// Heap baseline interval (ms). Every board in the CI smoke matrix emits this
// line so a heap regression on any target shows up in serial output.
#define BB_SMOKE_HEAP_LOG_INTERVAL_MS 5000

// Heap baseline SOURCE: emitted via bb_serialize_console_heap_report() --
// gather (bb_meminfo) -> render (bb_serialize_walk over
// bb_serialize_console_heap_desc) -> bb_log_i(), all internal to that call.
// Measured, not published — serial only. Runs as a bb_timer MODE-A job on
// the shared bb_timer_disp task — no dedicated task.
static void heap_log_tick(void *arg)
{
    (void)arg;
    bb_serialize_console_heap_report("tick");
}
#endif // ESP_PLATFORM

void smoke_app_setup(void) {
    // bb_settings_creds_boot_init() is codegen-composed (tier=early,
    // components/bb_settings/include/bb_settings.h) and already ran via
    // bb_app_init_early() before smoke_app_setup() is called
    // (examples/smoke/main/entry_espidf.c) -- do not call it again here.
    bb_log_i(TAG, "boot");

    uint32_t boot_count = 0;
    bb_err_t boot_rc = bb_config_get_u32(&s_boot_count_field, &boot_count);
    if (boot_rc != BB_OK) {
        // NOT_FOUND is already resolved to BB_OK via has_default/def.u32
        // above -- a non-BB_OK return here is a genuine backend error
        // (e.g. width/type mismatch), which leaves boot_count untouched.
        // Fall back to the field's own default explicitly rather than
        // relying on the local zero-init to happen to match it.
        bb_log_w(TAG, "boot_count: get failed (%d), using default", (int)boot_rc);
        boot_count = s_boot_count_field.def.u32;
    }
    boot_count++;
    bb_config_set_u32(&s_boot_count_field, boot_count);
    bb_log_i(TAG, "boot=%lu", (unsigned long)boot_count);

    bb_wifi_set_hostname("bb-smoke");
    // WiFi init, HTTP server start, and route registration (GET /ping, GET
    // /ws, POST /api/wsbcast) are all handled by bb_app_init_early()
    // (bb_wifi_autoinit) and bb_app_init_rest() (bb_http_autostart_init,
    // then the regular-tier route registrations composed from
    // examples/smoke/main/bb_wire.h) -- the `bbtool codegen`-generated
    // composition root.

#ifdef ESP_PLATFORM
    // bb_meminfo heap baseline: boot line immediately, then hand off to a
    // bb_timer MODE-A periodic job on the shared bb_timer_disp task.
    heap_log_tick(NULL);
    {
        bb_periodic_timer_t heap_log_timer = NULL;
        bb_err_t herr = bb_timer_deferred_periodic_create(
            heap_log_tick, NULL, "heap_log", &heap_log_timer);
        if (herr == BB_OK) {
            bb_timer_periodic_start(heap_log_timer,
                                    (uint64_t)BB_SMOKE_HEAP_LOG_INTERVAL_MS * 1000ULL);
        } else {
            bb_log_w(TAG, "heap_log: timer create failed (%d)", (int)herr);
        }
    }

    // bb_temp: /api/health "temp" section (present=false on unsupported
    // targets, e.g. classic ESP32) is registered by the codegen-composed
    // bb_temp_autoregister_init() (tier=regular, components/bb_temp/include/
    // bb_temp.h), which already ran via bb_app_init_rest() before
    // smoke_app_setup() is called -- do not call bb_temp_register_info()
    // again here.

    // bb_ota_check: link-load only. No URL set, so polling stays idle and
    // bb_ota_check_now() returns BB_ERR_INVALID_STATE cleanly. Consumers
    // (TaipanMiner, snugfeather) call bb_ota_check_set_releases_url(...).
    if (bb_ota_check_init(NULL) != BB_OK) {
        bb_log_w(TAG, "bb_ota_check: init failed");
    }

    // bb_ws_server: /ws echo + /api/wsbcast broadcast demo -- registration
    // is codegen-composed (examples/smoke/main/bb_wire.h), see the comment
    // above bb_wifi_set_hostname().

    // bb_embed_site smoke: register the demo SPA assets to prove the
    // codegen→C→link path compiles correctly on every ESP-IDF board target.
    {
        size_t n = 0;
        const bb_http_asset_t *assets = demo_site_get(&n);
        bb_err_t rc = bb_http_register_assets(bb_http_server_get_handle(), assets, n);
        if (rc == BB_OK) {
            bb_log_i(TAG, "bb_embed_site: registered %u demo_site assets", (unsigned)n);
        } else {
            bb_log_w(TAG, "bb_embed_site: register_assets failed (%d)", (int)rc);
        }
    }
#endif
}

void smoke_app_loop(void) {
    bb_http_server_poll();
}
